type Key = keyof typeof en;

/**
 * Card PERF1a: only the page's language is downloaded. English is this module (the default, in the main chunk); the
 * Turkish table is its own chunk (`i18n-tr.ts`), loaded before the site starts when the saved language is Turkish
 * (`loadLang` in main.ts) and on a switch to Turkish (`setLang`). Until it is in, `t()` answers in English.
 */
let trTable: Record<Key, string> | null = null;
let trLoading: Promise<boolean> | null = null;

/** Loads the Turkish table once; false when its chunk can't load (offline, a deploy replaced it): English stays. */
function loadTurkish(): Promise<boolean> {
  if (trTable) return Promise.resolve(true);
  trLoading ??= loadChunk(() => import('./i18n-tr.ts')).then((m) => {
    trTable = m?.tr ?? null;
    trLoading = null;
    return trTable !== null;
  });
  return trLoading;
}

/**
 * The default language is English on every device, whatever the browser's language (owner, 2 Nov 2026: "English
 * first"); a chosen language (TR / EN in the profile menu or the top bar) is remembered under 'lang', shared by every
 * page of the site (site, extension page, privacy) and passed to the extension through site-bridge.
 */
function detect(): Lang {
  return load('lang') === 'tr' ? 'tr' : 'en';
}

let current: Lang = detect();

/**
 * Before the site draws (main.ts, after the settings are in step with the extension): reads the saved language again
 * and loads its table, so the first frame is already in the right language.
 */
export async function loadLang(): Promise<void> {
  current = detect();
  if (current === 'tr' && !(await loadTurkish())) current = 'en';
  document.documentElement.lang = current;
}

/** Fetches the Turkish table ahead (a hover on the language switch), so the switch itself is instant. */
export function warmLang(next: Lang): void {
  if (next === 'tr') void loadTurkish();
}

export function lang(): Lang {
  return current;
}

export function t(key: Key, params: Record<string, string | number> = {}): string {
  return (current === 'tr' && trTable ? trTable : en)[key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}

export type { Key as I18nKey };

export function isKey(key: string): key is Key {
  return key in en;
}

/** The help page in the site's language, optionally at a section (card 7; the page maps ids to its Turkish block). */
export function helpHref(section?: string): string {
  return `/help.html?lang=${current}${section ? `#${section}` : ''}`;
}

/** data-i18n="anahtar" ve data-i18n-placeholder="anahtar" olan öğelerin metnini günceller. */
export function translate(root: ParentNode = document): void {
  // Gizlilik sayfası sitenin o anki dilinde açılsın.
  // A section (card SIMP1: `data-privacy-link="voice"`) keeps its anchor; the Turkish block's ids end in `-tr`.
  for (const link of root.querySelectorAll<HTMLAnchorElement>('a[data-privacy-link]')) {
    const section = link.dataset.privacyLink;
    link.href = `/privacy.html?lang=${current}${section ? `#${section}${current === 'tr' ? '-tr' : ''}` : ''}`;
  }
  // The terms of use too (card TOS).
  for (const link of root.querySelectorAll<HTMLAnchorElement>('a[data-terms-link]')) link.href = `/terms.html?lang=${current}`;
  // The help page too (card 7), keeping a section anchor such as #connection.
  for (const link of root.querySelectorAll<HTMLAnchorElement>('a[data-help-link]')) link.href = helpHref(link.dataset.helpLink);
  // And the Thanks page (card 11).
  for (const link of root.querySelectorAll<HTMLAnchorElement>('a[data-thanks-link]')) link.href = `/thanks.html?lang=${current}`;
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = el.dataset.i18n!;
    if (isKey(key)) el.textContent = t(key);
  }
  for (const el of root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]')) {
    const key = el.dataset.i18nPlaceholder!;
    if (!isKey(key)) continue;
    el.placeholder = t(key);
    // Etiketi olmayan kutular ekran okuyucuda yer tutucu metniyle anılsın (yer tutucu yazınca kaybolur).
    if (!el.labels?.length) el.setAttribute('aria-label', t(key));
  }
  // Başlık (üstüne gelince) ve ekran okuyucu etiketi
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    const key = el.dataset.i18nTitle!;
    if (isKey(key)) {
      el.title = t(key);
      el.setAttribute('aria-label', t(key));
    }
  }
}

export async function setLang(next: Lang): Promise<void> {
  if (next === 'tr' && !(await loadTurkish())) return;
  current = next;
  save('lang', next);
  document.documentElement.lang = next;
  translate();
  window.dispatchEvent(new Event('langchange'));
}
