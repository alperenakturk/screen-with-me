const dictionaries: Record<Lang, Record<Key, string>> = { tr, en };

/**
 * Varsayılan dil Türkçe (kullanıcı EN seçerse o hatırlanır). Seçim tarayıcıda 'lang' anahtarıyla saklanır ve
 * aynı adresteki tüm sayfalar (site, eklenti sayfası, gizlilik) bunu paylaşır;
 * eklenti de site-bridge üzerinden aynı dili alır.
 */
function detect(): Lang {
  const saved = load('lang');
  return saved === 'en' ? 'en' : 'tr';
}

let current: Lang = detect();

export function lang(): Lang {
  return current;
}

export function t(key: Key, params: Record<string, string | number> = {}): string {
  return dictionaries[current][key].replace(/\{(\w+)\}/g, (_, name: string) => String(params[name] ?? ''));
}

export type { Key as I18nKey };

export function isKey(key: string): key is Key {
  return key in tr;
}

/** data-i18n="anahtar" ve data-i18n-placeholder="anahtar" olan öğelerin metnini günceller. */
export function translate(root: ParentNode = document): void {
  // Gizlilik sayfası sitenin o anki dilinde açılsın.
  for (const link of root.querySelectorAll<HTMLAnchorElement>('a[data-privacy-link]')) link.href = `/privacy.html?lang=${current}`;
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n]')) {
    const key = el.dataset.i18n!;
    if (isKey(key)) el.textContent = t(key);
  }
  for (const el of root.querySelectorAll<HTMLInputElement>('[data-i18n-placeholder]')) {
    const key = el.dataset.i18nPlaceholder!;
    if (isKey(key)) el.placeholder = t(key);
  }
  // Başlık (üstüne gelince) ve ekran okuyucu etiketi
  for (const el of root.querySelectorAll<HTMLElement>('[data-i18n-title]')) {
    const key = el.dataset.i18nTitle!;
    if (isKey(key)) {
      el.title = t(key);
      el.setAttribute('aria-label', t(key));
    }
  }
}

export function setLang(next: Lang): void {
  current = next;
  save('lang', next);
  document.documentElement.lang = next;
  translate();
  window.dispatchEvent(new Event('langchange'));
}
